    ON public.user_course_performance(curriculum_course_id);

-- Final invariant check: every surviving performance row must now be both in
-- its user's curriculum and at or before that batch's completed term.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM public.user_course_performance ucp
        JOIN public.users u ON u.user_id = ucp.user_id
        JOIN public.batch_progress bp ON bp.batch_year = u.batch AND bp.dept_code = u.dept_code
        JOIN public.curriculum_courses cc ON cc.curriculum_course_id = ucp.curriculum_course_id
        JOIN public.academic_terms result_term ON result_term.term_code = cc.term_code
        LEFT JOIN public.academic_terms completed_term ON completed_term.term_code = bp.latest_completed_term_code
        WHERE cc.curriculum_id <> bp.curriculum_id
           OR completed_term.term_order IS NULL
           OR result_term.term_order > completed_term.term_order
    ) THEN
        RAISE EXCEPTION 'Post-migration performance invariant failed';
    END IF;
END;
$$;

COMMIT;
