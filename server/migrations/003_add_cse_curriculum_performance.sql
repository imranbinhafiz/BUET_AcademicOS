    dept_code character varying(10) NOT NULL,
    curriculum_id integer NOT NULL,
    current_term_code character varying(10),
    latest_completed_term_code character varying(10),
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT batch_progress_pkey PRIMARY KEY (batch_year, dept_code),
    CONSTRAINT batch_progress_batch_year_check CHECK (batch_year ~ '^[0-9]{4}$'),
    CONSTRAINT batch_progress_dept_curriculum_fkey
