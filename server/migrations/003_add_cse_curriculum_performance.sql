-- This first version is deliberately defined before legacy UCP migration.
-- It is replaced with the stronger saved-result guard after UCP gets its
-- curriculum_course_id column below.
CREATE OR REPLACE FUNCTION public.validate_batch_progress()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_current_order smallint;
    v_completed_order smallint;
BEGIN
    IF NEW.current_term_code IS NOT NULL THEN
        SELECT term_order INTO v_current_order
        FROM public.academic_terms
        WHERE term_code = NEW.current_term_code;
    END IF;

    IF NEW.latest_completed_term_code IS NOT NULL THEN
        SELECT term_order INTO v_completed_order
        FROM public.academic_terms
        WHERE term_code = NEW.latest_completed_term_code;
    END IF;

    IF NEW.current_term_code IS NOT NULL
       AND NEW.latest_completed_term_code IS NOT NULL
       AND v_completed_order >= v_current_order THEN
        RAISE EXCEPTION 'Latest completed term % must be earlier than current term %',
            NEW.latest_completed_term_code, NEW.current_term_code;
    END IF;

    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_batch_progress
    BEFORE INSERT OR UPDATE ON public.batch_progress
    FOR EACH ROW EXECUTE FUNCTION public.validate_batch_progress();

