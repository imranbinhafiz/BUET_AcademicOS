-- AcademicOS performance migration 003
--
-- One-time forward migration for the existing buet_academicos database after
-- migrations 001 and 002. It introduces a CSE curriculum placement model so
-- performance data is term-aware, batch-controlled, and safe for repeated
-- courses such as CSE 400/CSE 450.
--
-- Run with ON_ERROR_STOP enabled. The transaction rolls back completely if a
-- preflight check fails. Do not rerun this migration after it succeeds.

BEGIN;

DO $$
BEGIN
    IF current_database() <> 'buet_academicos' THEN
        RAISE EXCEPTION 'Migration 003 must run on buet_academicos, not %', current_database();
    END IF;

    IF to_regclass('public.users') IS NULL
       OR to_regclass('public.courses') IS NULL
       OR to_regclass('public.user_course_performance') IS NULL THEN
        RAISE EXCEPTION 'Migration 003 requires the schema created by migrations 001 and 002';
    END IF;

    IF to_regclass('public.academic_terms') IS NOT NULL
       OR to_regclass('public.curricula') IS NOT NULL
       OR to_regclass('public.curriculum_courses') IS NOT NULL
       OR to_regclass('public.batch_progress') IS NOT NULL THEN
        RAISE EXCEPTION 'Migration 003 appears to have already been applied; do not run it again';
    END IF;
END;
$$;

