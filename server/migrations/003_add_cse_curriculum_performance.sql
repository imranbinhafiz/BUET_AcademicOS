CREATE TABLE public.academic_terms (
    term_code character varying(10) PRIMARY KEY,
    term_order smallint NOT NULL UNIQUE,
    level_no smallint NOT NULL CHECK (level_no BETWEEN 1 AND 4),
    term_no smallint NOT NULL CHECK (term_no BETWEEN 1 AND 2),
    display_name character varying(50) NOT NULL,
    CONSTRAINT academic_terms_code_format_check CHECK (term_code ~ '^[1-4]-[1-2]$'),
    CONSTRAINT academic_terms_order_check CHECK (term_order = ((level_no - 1) * 2 + term_no))
);

CREATE TABLE public.curricula (
    curriculum_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_code character varying(10) NOT NULL,
    curriculum_version character varying(50) NOT NULL,
    name character varying(255) NOT NULL,
    source_title character varying(255),
    is_active boolean NOT NULL DEFAULT TRUE,
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT curricula_dept_version_key UNIQUE (dept_code, curriculum_version),
    CONSTRAINT curricula_id_dept_code_key UNIQUE (curriculum_id, dept_code),
    CONSTRAINT curricula_dept_code_fkey
        FOREIGN KEY (dept_code) REFERENCES public.departments(dept_code)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- A curriculum placement is separate from the global course catalogue. The
-- placement ID, rather than course code alone, distinguishes repeat courses
-- in different terms and snapshots the credit used in GPA calculations.
CREATE TABLE public.curriculum_courses (
    curriculum_course_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curriculum_id integer NOT NULL,
    term_code character varying(10) NOT NULL,
    course_code character varying(20) NOT NULL,
    credits_at_placement numeric(3,2) NOT NULL CHECK (credits_at_placement > 0),
    course_type character varying(20) NOT NULL,
    is_required boolean NOT NULL DEFAULT TRUE,
    theory_hours numeric(4,2) NOT NULL DEFAULT 0 CHECK (theory_hours >= 0),
    sessional_hours numeric(4,2) NOT NULL DEFAULT 0 CHECK (sessional_hours >= 0),
    CONSTRAINT curriculum_courses_course_type_check
        CHECK (course_type IN ('theory', 'sessional', 'project', 'thesis', 'other')),
    CONSTRAINT curriculum_courses_unique_placement UNIQUE (curriculum_id, term_code, course_code),
    CONSTRAINT curriculum_courses_curriculum_id_fkey
        FOREIGN KEY (curriculum_id) REFERENCES public.curricula(curriculum_id)
        ON DELETE RESTRICT,
    CONSTRAINT curriculum_courses_term_code_fkey
        FOREIGN KEY (term_code) REFERENCES public.academic_terms(term_code)
        ON DELETE RESTRICT,
    CONSTRAINT curriculum_courses_course_code_fkey
        FOREIGN KEY (course_code) REFERENCES public.courses(course_code)
        ON DELETE RESTRICT
);

-- This is controlled by an administrator: it describes what each batch has
-- completed, rather than guessing from the wall calendar. current_term_code
